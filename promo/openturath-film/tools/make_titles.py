"""Pick real short titles from the app's bundled catalogs for the 3D book spines.

Source: openturath_ai/assets/data/*_KATALOG_*.json (field "الاسم_المختصر").
Output: src/titles.ts
"""
import glob, json, os, random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "..", "..", "openturath_ai", "assets", "data")
seen, pool = set(), []
for f in sorted(glob.glob(os.path.join(DATA, "[0-9]*_KATALOG_*.json"))):
    for b in json.load(open(f, encoding="utf-8")):
        t = (b.get("الاسم_المختصر") or "").strip()
        if 4 <= len(t) <= 20 and t not in seen and not any(c.isdigit() for c in t) and "[" not in t:
            seen.add(t)
            pool.append(t)
random.seed(7)
ROWS, COLS, HERO_ROW, HERO_COL = 6, 42, 3, 21
N = ROWS * COLS
HERO_I = HERO_ROW * COLS + HERO_COL
picked = random.sample(pool, N)
HERO = "منهاج الطالبين"
assert HERO in seen
picked = [t for t in picked if t != HERO][: N - 1]
picked.insert(HERO_I, HERO)
with open(os.path.join(ROOT, "src", "titles.ts"), "w", encoding="utf-8") as out:
    out.write("// Generated by tools/make_titles.py from the app's bundled catalog JSON. Do not edit.\n")
    out.write(f"export const ROWS = {ROWS};\nexport const COLS = {COLS};\nexport const HERO_ROW = {HERO_ROW};\nexport const HERO_COL = {HERO_COL};\n")
    out.write("export const TITLES: string[] = " + json.dumps(picked, ensure_ascii=False, indent=1) + ";\n")
print(len(picked), "titles; pool", len(pool))
